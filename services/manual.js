const STYLE = {
  h2: 'margin:0 0 0.6em;font-size:1.35em;line-height:1.4;color:#2e2925;',
  h3: 'margin:1.25em 0 0.35em;font-size:1.12em;line-height:1.5;color:#342f2b;',
  p: 'margin:0.55em 0;line-height:1.75;',
  ul: 'margin:0.55em 0;padding-left:1.45em;',
  ol: 'margin:0.55em 0;padding-left:1.45em;',
  li: 'margin:0.3em 0;line-height:1.7;',
  table: 'width:100%;max-width:100%;margin:0.8em 0;border-collapse:collapse;table-layout:auto;font-size:0.94em;',
  th: 'border:1px solid #e7ddd0;padding:6px 8px;background:#faf6ef;text-align:left;vertical-align:top;',
  td: 'border:1px solid #e7ddd0;padding:6px 8px;text-align:left;vertical-align:top;word-break:break-word;',
  pre: 'max-width:100%;margin:0.8em 0;padding:10px 12px;overflow-x:auto;background:#f7f3ed;border:1px solid #e7ddd0;border-radius:8px;white-space:pre-wrap;word-break:break-all;',
  code: 'font-size:0.88em;word-break:break-all;',
  a: 'color:#c9563d;word-break:break-all;'
}

function escapeHtml(value) {
  return String(value || '').replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

function inline(value) {
  return escapeHtml(value)
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/`([^`]+)`/g, `<code style="${STYLE.code}">$1</code>`)
    .replace(/\[([^\]]+)]\((https?:\/\/[^)]+)\)/g, `<a style="${STYLE.a}" href="$2">$1</a>`)
}

function tableCells(line) {
  return String(line).replace(/^\|/, '').replace(/\|$/, '').split('|').map((cell) => cell.trim())
}

function isTableDivider(cells) {
  return cells.length > 0 && cells.every((cell) => /^:?-{3,}:?$/.test(cell))
}

function chapterHtml(lines) {
  const out = []
  let paragraph = []
  let list = []
  let listType = ''
  let table = []
  let code = []
  let inCode = false

  function flushParagraph() {
    if (!paragraph.length) return
    out.push(`<p style="${STYLE.p}">${inline(paragraph.join(' '))}</p>`)
    paragraph = []
  }
  function flushList() {
    if (!list.length) return
    const tag = listType === 'ol' ? 'ol' : 'ul'
    out.push(`<${tag} style="${STYLE[tag]}">${list.map((item) => `<li style="${STYLE.li}">${inline(item)}</li>`).join('')}</${tag}>`)
    list = []
    listType = ''
  }
  function flushTable() {
    if (!table.length) return
    const header = table[0]
    const rows = table.slice(1)
    const cells = (row, tag) => row.map((cell, index) => `<${tag} style="${STYLE[tag]}${index === 0 ? 'width:4em;white-space:nowrap;' : ''}">${inline(cell)}</${tag}>`).join('')
    out.push(`<table style="${STYLE.table}"><thead><tr>${cells(header, 'th')}</tr></thead><tbody>${rows.map((row) => `<tr>${cells(row, 'td')}</tr>`).join('')}</tbody></table>`)
    table = []
  }
  function flushAll() { flushParagraph(); flushList(); flushTable() }

  for (const raw of lines) {
    const line = raw.trim()
    if (inCode) {
      if (line.startsWith('```')) {
        out.push(`<pre style="${STYLE.pre}"><code style="${STYLE.code}">${escapeHtml(code.join('\n'))}</code></pre>`)
        code = []
        inCode = false
      } else code.push(raw)
      continue
    }
    if (line.startsWith('```')) { flushAll(); inCode = true; continue }
    if (!line) { flushAll(); continue }
    if (line.startsWith('### ')) {
      flushAll()
      out.push(`<h3 style="${STYLE.h3}">${inline(line.slice(4))}</h3>`)
      continue
    }
    if (line.startsWith('|')) {
      flushParagraph(); flushList()
      const cells = tableCells(line)
      if (!isTableDivider(cells)) table.push(cells)
      continue
    }
    if (line.startsWith('- ')) {
      flushParagraph(); flushTable()
      if (listType && listType !== 'ul') flushList()
      listType = 'ul'
      list.push(line.slice(2))
      continue
    }
    if (/^\d+\.\s+/.test(line)) {
      flushParagraph(); flushTable()
      if (listType && listType !== 'ol') flushList()
      listType = 'ol'
      list.push(line.replace(/^\d+\.\s+/, ''))
      continue
    }
    flushList(); flushTable()
    paragraph.push(line)
  }
  flushAll()
  if (inCode && code.length) out.push(`<pre style="${STYLE.pre}"><code>${escapeHtml(code.join('\n'))}</code></pre>`)
  return out.join('')
}

function parseManual(markdown) {
  const chapters = []
  let current = null
  for (const line of String(markdown || '').replace(/\r\n/g, '\n').split('\n')) {
    if (line.startsWith('## ')) {
      if (current) chapters.push(current)
      current = { title: line.slice(3).trim(), lines: [] }
    } else if (current) current.lines.push(line)
  }
  if (current) chapters.push(current)
  if (chapters.length !== 8) return []
  return chapters.map((chapter, index) => ({
    id: `ch${index + 1}`,
    title: chapter.title,
    html: `<h2 style="${STYLE.h2}">${inline(chapter.title)}</h2>${chapterHtml(chapter.lines)}`
  }))
}

function loadBundled() {
  return parseManual(MANUAL_MARKDOWN)
}

